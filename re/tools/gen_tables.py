"""Generate src/tables.h and docs/tables.md: named views (address, length,
element kind) into the loaded PRG[] for every ROM data table named in
tools/symbols.py. No table bytes are copied: the C code reads them from
PRG[] at run time (see CLAUDE.md, ROM policy).

Length: exact where disasm_cfg.DATA_EXTENTS proves it (or for jump tables,
JUMP_TABLES); otherwise an upper bound, up to the next named symbol
(symbols.py) or the next byte classified as something else. Bytes past a
table's referenced start may still be 'unknown' in docs/codemap.json. Kind: 'word'
for jump tables, else 'byte'.

Run after `make listing` (it reads docs/codemap.json)."""
import json
import os

import disasm_cfg
import symbols

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = 0xC000

# exact lengths: proven data extents and jump tables (both from disasm_cfg)
LENGTHS = {a: (n, why) for a, (n, why) in disasm_cfg.DATA_EXTENTS.items()}
LENGTHS.update({a: (2 * n, why) for a, (n, consumer, why) in disasm_cfg.JUMP_TABLES.items()})


def is_table(name):
    return name.startswith('tbl_') or 'table' in name or \
        name in ('enemy_spawn_x', 'enemy_spawn_y', 'player_spawn_x', 'player_spawn_y')


def main():
    cls = json.load(open(os.path.join(ROOT, 'docs', 'codemap.json')))['classes']
    labels = set(symbols.CODE_DEFS)
    rows = []
    for a, (name, status, note) in sorted(symbols.CODE_DEFS.items()):
        if not is_table(name):
            continue
        c0 = cls[a - BASE]
        if c0 not in 'DJ':
            raise SystemExit('$%04X %s: class %s, not data' % (a, name, c0))
        if a in LENGTHS:
            n, how = LENGTHS[a]
        else:
            e = a + 1
            while e <= 0xFFFF and cls[e - BASE] in (c0, '?') and e not in labels:
                e += 1
            n, how = e - a, 'upper bound (next named symbol or classified byte)'
        kind = 'word' if c0 == 'J' else 'byte'
        rows.append((a, name, n, kind, status, how, note))

    h = ['/* GENERATED by tools/gen_tables.py from tools/symbols.py and the listing.',
         ' * Do not edit: rename or add tables in symbols.py, then `make listing` and',
         ' * rerun the script. Each table is a view into PRG[] (machine.h): NAME is',
         ' * its CPU address, NAME_LEN its length in bytes. */',
         '#ifndef BC_TABLES_H', '#define BC_TABLES_H', '']
    for a, name, n, kind, status, how, note in rows:
        m = name.upper()
        h.append('#define %-24s 0x%04X  /* %s, %s%d bytes%s; %s */' % (
            m, a, kind, '' if a in LENGTHS else '<= ', n,
            ' (%d entries)' % (n // 2) if kind == 'word' else '', status))
        h.append('#define %-24s %d' % (m + '_LEN', n))
    h += ['', '#endif', '']
    open(os.path.join(ROOT, 'src', 'tables.h'), 'w').write('\n'.join(h))

    d = ['# ROM data tables', '',
         'GENERATED by `tools/gen_tables.py`; the C names are in `src/tables.h`. '
         'Every table is read from the loaded ROM at run time; none is copied into the source.', '',
         '| Address | Name | Bytes | Kind | Status | Length from | Note |', '|---|---|---|---|---|---|---|']
    for a, name, n, kind, status, how, note in rows:
        d.append('| `$%04X` | `%s` | %d | %s | %s | %s | %s |' % (
            a, name, n, kind, status, how, note.replace('|', '\\|')))
    open(os.path.join(ROOT, 'docs', 'tables.md'), 'w').write('\n'.join(d) + '\n')
    print('wrote src/tables.h and docs/tables.md: %d tables' % len(rows))


if __name__ == '__main__':
    main()
