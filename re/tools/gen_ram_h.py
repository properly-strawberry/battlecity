"""Generate src/ram.h (named RAM variables) from tools/symbols.py.

Scalars become  #define name RAM[0xADDR]  (an lvalue);
arrays become   #define name (RAM + 0xADDR)  (index with name[i]).
Run after editing symbols.py."""
import os

import symbols

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = ['/* GENERATED by tools/gen_ram_h.py from tools/symbols.py -- do not edit.',
       ' * Every game variable at its original CPU address. [prior] = name imported',
       " * from the user's earlier decomp, not yet re-verified here. */",
       '#ifndef BC_RAM_H', '#define BC_RAM_H', '#include "machine.h"', '']
for a, (n, size, status, note) in sorted(symbols.RAM_DEFS.items()):
    note = note.replace('*/', '* /')
    tag = '' if status == 'verified' else ' [prior]'
    if size == 1:
        out.append('#define %-24s RAM[0x%04X]   /* %s%s */' % (n, a, note[:90], tag))
    else:
        out.append('#define %-24s (RAM + 0x%04X) /* [%d] %s%s */' % (n, a, size, note[:84], tag))
out += ['', '/* aliases: the same byte reused for an unrelated purpose */']
for al in symbols.ALIASES:
    a, n, note = al[:3]
    size = al[3] if len(al) > 3 else 1
    note = note.replace('*/', '* /')[:84]
    if size == 1:
        out.append('#define %-24s RAM[0x%04X]   /* %s */' % (n, a, note))
    else:
        out.append('#define %-24s (RAM + 0x%04X) /* [%d] %s */' % (n, a, size, note))
out += ['', '/* ROM data by original address ($C000-$FFFF) */',
        '#define ROM8(addr) (PRG[(addr) - 0xC000])', '', '#endif']
open(os.path.join(ROOT, 'src', 'ram.h'), 'w').write('\n'.join(out) + '\n')
print('wrote src/ram.h: %d variables' % len(symbols.RAM_DEFS))
